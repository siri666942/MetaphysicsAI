    classical = random.sample(CLASSICAL_CORPUS, min(5, len(CLASSICAL_CORPUS)))
    lines = [
        "---",
        "【启示语参考·必做】本次八字分析回复的**最后一段**必须是「启示赠言」，要求：",
        "1. 仿照下方【现代文】或【七言体】的句式、意境与气质（带一点悖论、留白、不说教）。",
        "2. 二选一：要么写 1～2 句现代文风格（不要写成「命由天定运由己造」这类常规励志句）；要么写四句七言体。",
        "3. 不要照抄下面例句。",
        "【现代文】",
    ]
    for i, s in enumerate(modern, 1):
        lines.append(f"{i}. {s}")
    lines.append("【七言体】")
    for i, s in enumerate(classical, 1):
        lines.append(f"{i}. {s}")
    return "\n".join(lines)
